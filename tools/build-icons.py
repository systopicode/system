#!/usr/bin/env python3
"""Rebuild the local icon subset from verified, pinned upstream archives.
No runtime package dependency. Usage: python3 tools/build-icons.py --archives-dir /tmp/icons
Download tabler.tgz / solar.tgz / phosphor.tgz from the URLs pinned in docs/icon-migration/assets.json first.
Use --check for a read-only reproducibility check.
"""
from pathlib import Path
import argparse,base64,copy,hashlib,json,re,tarfile,csv,io,shutil,tempfile,xml.etree.ElementTree as E
parser=argparse.ArgumentParser();parser.add_argument('--archives-dir',type=Path,required=True);parser.add_argument('--check',action='store_true');args=parser.parse_args()
S=Path(__file__).resolve().parents[1]
registry=json.loads((S/'src/Ui/icon-map.json').read_text());m=registry['outline'];sm=registry['duotone']
manifest=json.loads((S/'docs/icon-migration/assets.json').read_text());assets=[];generated={}
workspace=tempfile.TemporaryDirectory(prefix='fluxo-icon-build-');B=Path(workspace.name)
for name in ['tabler','solar','phosphor']:
    archive=args.archives_dir/(name+'.tgz');expected=manifest['packages'][name]['integrity']
    actual='sha512-'+base64.b64encode(hashlib.sha512(archive.read_bytes()).digest()).decode()
    if actual!=expected:raise SystemExit('Integrity mismatch: '+name)
    target=B/name;target.mkdir()
    # Extract only regular files, with an explicit path boundary (also works on Python 3.9).
    with tarfile.open(archive) as tar:
        for member in tar.getmembers():
            if member.isdir(): continue
            if not member.isfile(): raise SystemExit('Non-regular archive entry: '+member.name)
            dest=(target/member.name).resolve()
            if not str(dest).startswith(str(target.resolve())+'/'): raise SystemExit('Archive path escapes root')
            dest.parent.mkdir(parents=True,exist_ok=True)
            with tar.extractfile(member) as source, dest.open('wb') as output: shutil.copyfileobj(source,output)
T=B/'tabler/package/icons/outline';solar=json.loads((B/'solar/package/icons.json').read_text())
def put(repo,rel,text):
    generated[rel]=('\n'.join(line.rstrip() for line in text.splitlines()).rstrip()+'\n').encode()
css='''/* Generated by tools/build-icons.py. Tabler Icons 3.50.0 (MIT); Solar 1.2.13 (CC BY 4.0); Phosphor 2.1.1 (MIT).
 * Copyright and modification notices: legal/third-party/ and docs/icon-migration/.
 * Local SVG masks keep dynamic and server-rendered <i> slots consistent, including shadow roots. */
:root, :host {\n'''
E.register_namespace('', 'http://www.w3.org/2000/svg')
for target in sorted(set(m.values())):
    provider='solar' if target in solar['icons'] else 'tabler'
    if provider=='solar':
        body=solar['icons'][target]['body'].replace('stroke-width="1.5"','stroke-width="2"')
        # The retained small Solar information hint is monochrome.
        if target in ('info-circle-line-duotone',): body=re.sub(r'\sopacity="[^"]*"', '', body)
        text='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">'+body+'</svg>\n'
    else:
        source=(T.parent/'filled'/(registry['tablerFilled'][target]+'.svg')) if target in registry.get('tablerFilled',[]) else T/(target+'.svg')
        text=source.read_text();text=re.sub(r'\sclass="[^"]*"','',text)
    put('system','public/icons/'+provider+'/'+target+'.svg',text)
    css+=f'  --icon-{target}: url("../icons/{provider}/{target}.svg");\n'
for alias,target in registry.get('cssAliases',{}).items():
    if target not in set(m.values()): raise SystemExit('Unregistered CSS icon alias: '+target)
    css+=f'  --icon-{alias}: var(--icon-{target});\n'
css+='}\n'
css+='''.cmsIcon { --icon-mask: var(--icon-help-circle); --icon-primary: currentColor; --icon-secondary: currentColor; --icon-secondary-opacity: .7; display: inline-block; position: relative; flex: 0 0 auto; width: 1.25em; height: 1em; vertical-align: -.125em; font-style: normal; line-height: 1; text-indent: 0; }
.cmsIcon::before, .cmsIcon.cmsIcon-duotone::after { content: ""; display: block; position: absolute; left: 50%; top: 50%; width: 1.2em; height: 1.2em; transform: translate(-50%, -50%); background-color: var(--icon-primary); -webkit-mask: var(--icon-mask) center / contain no-repeat; mask: var(--icon-mask) center / contain no-repeat; }
.cmsIcon.cmsIcon-duotone::after { background-color: var(--icon-secondary); opacity: var(--icon-secondary-opacity); -webkit-mask-image: var(--icon-secondary-mask, none); mask-image: var(--icon-secondary-mask, none); }
.cmsIcon.cmsIcon-duotone { isolation: isolate; }
.cmsIcon.cmsIcon-duotone::before { z-index: 1; }
.cmsIcon.cmsIcon-duotone::after { z-index: 0; }
.cmsIcon.thumbBroken::before { -webkit-mask-size: 1em 1em; mask-size: 1em 1em; }
.cmsIcon-spin { animation: icon-spin 1s linear infinite; }
@keyframes icon-spin { to { transform: rotate(360deg); } }
@media (prefers-reduced-motion: reduce) { .cmsIcon.thumbBroken::before { -webkit-mask-size: 1em 1em; mask-size: 1em 1em; }
.cmsIcon-spin { animation: none; } }
@media (forced-colors: active) { .cmsIcon::before, .cmsIcon.cmsIcon-duotone::after { background-color: CanvasText; opacity: 1; } }
'''
for name,target in sorted(m.items()):css+=f'.cmsIcon-{name} {{ --icon-mask: var(--icon-{target}); }}\n'
# Derive opaque masks for independent primary / secondary theme colours, retaining ancestor geometry attributes.
def masknode(node,role,inherited=False):
 secondary=inherited or ('opacity' in node.attrib and float(node.attrib['opacity'])<1)
 dest=E.Element(node.tag,{k:v for k,v in node.attrib.items() if k!='opacity'})
 if len(node):
  for child in node:
   rendered=masknode(child,role,secondary)
   if rendered is not None:dest.append(rendered)
  return dest if len(dest) else None
 return dest if secondary==(role=='secondary') else None
for name,icon in sm.items():
 root=E.fromstring((B/'phosphor/package/assets/duotone'/f'{icon}-duotone.svg').read_text())
 for role in ['primary','secondary']:
  result=masknode(root,role);assert result is not None,(icon,role)
  text=E.tostring(result,encoding='unicode')+'\n';put('system',f'public/icons/phosphor/{icon}-{role}.svg',text)
 css+=f'.cmsIcon.cmsIcon-duotone.cmsIcon-{name} {{ --icon-mask: url("../icons/phosphor/{icon}-primary.svg"); --icon-secondary-mask: url("../icons/phosphor/{icon}-secondary.svg"); }}\n'
put('system','public/css/11_icons.css',css)


js=(S/'public/js/gui/icons.js').read_text()
js=re.sub(r'const keys = new Set\(\[.*?\]\), duotoneKeys = new Set\(\[.*?\]\);', 'const keys = new Set('+json.dumps(list(m))+'), duotoneKeys = new Set('+json.dumps(list(sm))+');', js)
generated['public/js/gui/icons.js']=js.encode()
for rel,data in generated.items():
    if rel.startswith('public/icons/') and rel.endswith('.svg'):
        E.fromstring(data)  # Reject malformed SVG before publishing generated assets.
        provider=rel.split('/')[2]
        assets.append({'path':rel,'provider':provider,'version':registry[provider+'Version'],'sha256':hashlib.sha256(data).hexdigest(),'source':manifest['packages'][provider]['tarball'],'changes':'original Phosphor Duotone geometry; separated primary/secondary masks' if provider=='phosphor' else 'upstream Filled variant; removed provider classes' if provider=='tabler' and Path(rel).stem in registry.get('tablerFilled',[]) else 'regular stroke 2 retained, removed provider classes' if provider=='tabler' else 'stroke 2; original Solar geometry rendered monochrome' if Path(rel).stem in ('info-circle-line-duotone',) else 'original stroke 1.5; separated opaque primary/secondary masks; luminance-mask geometry flattened where present'})
mapping=io.StringIO();writer=csv.writer(mapping,lineterminator="\n");writer.writerow(['key','style','upstream_asset','note'])
for key,asset in sorted(m.items()):writer.writerow([key,'Solar Line Duotone' if asset in solar['icons'] else 'Tabler Filled' if asset in registry.get('tablerFilled',[]) else 'Tabler Outline',asset,'photo library for image collections' if key=='images' else ''])
for key,asset in sorted(sm.items()):writer.writerow([key,'Phosphor Duotone',asset,'primary/secondary masks'])
generated['docs/icon-migration/icon-map.csv']=mapping.getvalue().encode()
manifest['assets']=sorted(assets,key=lambda a:a['path'])
manifest['artwork']=[{'path':'src/Auth/passkey-icons.tpl.php','provider':'phosphor','version':registry['phosphorVersion'],'sourceAssets':['fingerprint','user-focus','lock-open'],'sha256':hashlib.sha256((S/'src/Auth/passkey-icons.tpl.php').read_bytes()).hexdigest(),'changes':'original Duotone geometry, ink roles; existing animation timings preserved'}]
generated['docs/icon-migration/assets.json']=(json.dumps(manifest,indent=2)+'\n').encode()
for rel,data in generated.items():
    dest=S/rel
    if args.check:
        if not dest.is_file() or dest.read_bytes()!=data:raise SystemExit('Generated icon asset differs: '+rel)
    else:
        dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(data)
# Remove only generated SVG assets that fell out of the registry; never unrelated project assets.
expected={str(S/rel) for rel in generated if rel.startswith('public/icons/')}
for p in (S/'public/icons').glob('*/*.svg'):
    if str(p) not in expected:
        if args.check:raise SystemExit('Unregistered generated SVG: '+str(p))
        p.unlink()
print(('Verified' if args.check else 'Generated'),len(assets),'SVG assets from pinned, integrity-checked archives.')
